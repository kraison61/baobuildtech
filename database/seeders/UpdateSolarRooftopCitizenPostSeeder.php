<h2>โครงการโซล่าเซลล์ภาคประชาชน คืออะไร และรอบ 2569 ต่างจากเดิมตรงไหน</h2>
<p>โครงการโซล่าเซลล์ภาคประชาชน คือโครงการรับซื้อไฟฟ้าจากระบบผลิตไฟฟ้าพลังงานแสงอาทิตย์ที่ติดตั้งบนหลังคาบ้านอยู่อาศัย โดยเน้นให้เจ้าของบ้าน “ผลิตไฟใช้เองเป็นหลัก” (Self Consumption) แล้วจึงขายเฉพาะไฟฟ้าส่วนเกินที่ไหลย้อนเข้าระบบให้การไฟฟ้าฝ่ายจำหน่าย ไม่ใช่การติดตั้งเพื่อขายไฟทั้งหมด</p>
