<h2>สมัครออนไลน์โซล่าเซลล์ภาคประชาชน มีขั้นตอนอะไรบ้าง</h2>
<p>การสมัครออนไลน์เริ่มจากสมัครบัญชีผู้ใช้งานในระบบของการไฟฟ้า กรอกแบบคำขอขายไฟฟ้าพร้อมอัปโหลดเอกสาร รอผลพิจารณาภายใน 30 วัน ชำระค่าเชื่อมต่อระบบและลงนามสัญญาภายใน 30 วันหลังประกาศผล จากนั้นติดตั้งระบบ ขอเชื่อมต่อโครงข่าย เปลี่ยนมิเตอร์ และจ่ายไฟเข้าระบบภายในกำหนด SCOD</p>
<p><strong>ขั้นตอนตามระบบ PPIM ของ กฟภ. (พื้นที่ปทุมธานีและต่างจังหวัด)</strong></p>
<ol>
<li>สมัครบัญชีผู้ใช้งานในระบบ PPIM (เลือกประเภท “บุคคลทั่วไป”)</li>
<li>เข้าสู่ระบบ แล้วเลือกโครงการผลิตไฟฟ้าจากพลังงานแสงอาทิตย์ที่ติดตั้งบนหลังคา สำหรับภาคประชาชน (ยื่นคำขอตั้งแต่ปี 2569)</li>
<li>เลือกหมายเลข CA ของมิเตอร์ที่จะติดตั้ง กรอกแบบคำขอ และอัปโหลดเอกสารแนบให้ครบ</li>
<li>กฟภ. พิจารณาเอกสารและความพร้อมทางเทคนิคของระบบจำหน่าย แล้วแจ้งผลทางอีเมล</li>
<li>ประกาศรายชื่อผู้ผ่านการคัดเลือกในระบบ ภายใน 30 วันนับถัดจากวันที่ยื่นคำขอครบถ้วน</li>
<li>ผู้ผ่านการคัดเลือกชำระค่าเชื่อมต่อระบบโครงข่ายไฟฟ้า และส่งเอกสารต้นฉบับประกอบการลงนามสัญญาภายใน 30 วัน</li>
<li>ลงนามสัญญาซื้อขายไฟฟ้า (PPA) กับการไฟฟ้าเขตพื้นที่ โดยกำหนดวัน SCOD ภายในปี 2570</li>
<li>ติดตั้งระบบให้ตรงตามที่ยื่นไว้ แล้วยื่นขอเชื่อมต่อโครงข่ายไฟฟ้า</li>
<li>แจ้งการประกอบกิจการพลังงานที่ได้รับการยกเว้นไม่ต้องขอรับใบอนุญาต กับสำนักงาน กกพ.</li>
<li>การไฟฟ้าเข้าตรวจสอบระบบ เปลี่ยนมิเตอร์ และทดสอบการเชื่อมต่อครั้งแรก (First Synchronization)</li>
<li>จ่ายไฟเข้าระบบเชิงพาณิชย์ (COD) ไม่เกินวัน SCOD ที่ระบุในสัญญา</li>
</ol>
<p><strong>หมายเหตุจากหน้างาน:</strong> ระบบ PPIM จะตั้งสถานะคำขอเป็น “รออัปโหลดเอกสาร” ถ้าแนบเอกสารไม่ครบ (เลขคำขอขึ้นต้นด้วย D) ซึ่ง <strong>ยังไม่นับเป็นการยื่นที่สมบูรณ์</strong> ต้องอัปโหลดจนครบให้สถานะเปลี่ยนเป็น “รอตรวจสอบแบบคำขอ” ก่อน ลำดับคิวจึงเริ่มนับจริง</p>

<h2>ต้องเตรียมเอกสารและค่าใช้จ่ายอะไรบ้าง</h2>
<p>เอกสารหลักที่ต้องเตรียมคือบัตรประชาชน สำเนาทะเบียนบ้านของบ้านที่ติดตั้ง บิลค่าไฟฟ้าย้อนหลังไม่เกิน 3 เดือน แบบแปลนการติดตั้งและแผนภาพระบบไฟฟ้า (Single Line Diagram) ข้อมูลอุปกรณ์ที่ใช้ และหนังสือมอบอำนาจกรณีผู้ยื่นไม่ใช่เจ้าของมิเตอร์</p>
<p>ด้านค่าใช้จ่ายฝั่งการไฟฟ้า กฟภ. กำหนดค่าดำเนินการตรวจสอบการเชื่อมต่อระบบไว้ที่ <strong>2,000 บาท ไม่รวมภาษี หรือ 2,140 บาทรวมภาษีมูลค่าเพิ่ม 7%</strong> เรียกเก็บหลังจากคำขอผ่านการพิจารณาแล้ว ส่วนค่าอุปกรณ์และค่าติดตั้งระบบทั้งหมดเป็นภาระของเจ้าของบ้านเอง</p>
<p><strong>ข้อกำหนดทางเทคนิคที่มักถูกมองข้าม</strong></p>
<ul>
<li>อินเวอร์เตอร์ที่ใช้ต้องผ่านการขึ้นทะเบียนผลิตภัณฑ์กับการไฟฟ้า — ฝั่ง กฟภ. ตรวจรายชื่อได้ที่ <a href="https://smartlist.pea.co.th/products" target="_blank" rel="noopener noreferrer">smartlist.pea.co.th/products</a></li>
<li>ฝั่ง กฟน. กำหนดให้อุปกรณ์ควบคุมการจ่ายไฟไหลย้อนเข้าระบบ (Export Limiting Device: EXL) ต้องผ่านการทดสอบจาก กฟน.</li>
<li>การติดตั้งระบบกักเก็บพลังงาน (BESS) ร่วมกับโซลาร์รูฟท็อปในโครงการนี้ <strong>ไม่มีข้อห้าม</strong> ตามที่ กกพ. แจ้งไว้ แต่ต้องดำเนินการให้เป็นไปตามมาตรฐานทางวิศวกรรมของการไฟฟ้าฝ่ายจำหน่ายคู่สัญญา</li>
</ul>
<p>เลือกอุปกรณ์ผิดรุ่นตั้งแต่วันซื้อเท่ากับยื่นไม่ผ่าน หรือต้องเปลี่ยนอินเวอร์เตอร์ใหม่ทั้งชุด ควรให้ผู้ติดตั้งยืนยันรายการอุปกรณ์กับทะเบียนของการไฟฟ้า <strong>ก่อน</strong> เซ็นใบเสนอราคา</p>

<h2>ติดโซล่าเซลล์บนหลังคาต้องขออนุญาตดัดแปลงอาคารไหม</h2>
<p>ตามการแก้ไขกฎกระทรวงที่ออกตามความใน พ.ร.บ.ควบคุมอาคาร พ.ศ. 2522 ซึ่งคณะรัฐมนตรีอนุมัติหลักการเมื่อวันที่ 6 พฤษภาคม 2568 การติดตั้งแผงเซลล์แสงอาทิตย์บนหลังคาอาคารที่มีน้ำหนักรวมในบริเวณหนึ่งบริเวณใด <strong>ไม่เกิน 20 กิโลกรัมต่อตารางเมตร ไม่ถือเป็นการดัดแปลงอาคาร</strong> จึงไม่ต้องยื่นขอใบอนุญาตดัดแปลงอาคาร (แบบ อ.1)</p>
<p>แต่ “ไม่ต้องขออนุญาต” ไม่เท่ากับ “ไม่ต้องตรวจโครงสร้าง” — บ้านเก่า หลังคาเมทัลชีทบาง หรือโครงหลังคาไม้ ยังต้องประเมินกำลังรับน้ำหนักจริงก่อนติดตั้งเสมอ และการติดตั้งยังต้องไม่ขัดกับข้อบัญญัติท้องถิ่นหรือระเบียบของโครงการหมู่บ้าน</p>

