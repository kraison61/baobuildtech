<h3>รับถมดินลูกรังสำหรับถนนภายในและลานจอดรถ</h3>
<p>รับถมดินลูกรังเหมาะกับงานที่ต้องรับน้ำหนักรถวิ่ง ได้แก่ ถนนภายในโครงการ ลานจอดรถ ทางเข้าไซต์ก่อสร้าง และชั้นรองพื้นทาง เพราะลูกรังมีการคละขนาดเม็ดที่ดี บดอัดแล้วได้ความแน่นสูงและระบายน้ำได้ ต่างจากดินถมทั่วไปที่อุ้มน้ำและอ่อนตัวเมื่อโดนฝน</p>
<p>ราคารับถมดินลูกรังอยู่ที่ประมาณ 380–500 บาทต่อคิวแน่น สูงกว่าดินถมทั่วไปเพราะเป็นวัสดุคัดจากบ่อ จุดที่ต้องระวังมี 2 ข้อ หนึ่ง ลูกรังให้ประโยชน์เต็มที่ก็ต่อเมื่อบดอัดจริง ถ้าเทกองแล้วเกลี่ยเฉย ๆ จะเป็นหลุมเป็นบ่อภายในหน้าฝนแรก สอง ไม่ควรใช้ลูกรังถมทั้งแปลงถ้าตั้งใจจะปลูกต้นไม้ เพราะรากพืชชอนไชได้ยาก</p>
<h3>สองความเข้าใจผิดที่ทำให้งานถมพังตั้งแต่เริ่ม</h3>
<p><strong>ความเข้าใจผิดที่ 1: "อยากปลูกต้นไม้ ก็ให้ถมด้วยดินร่วนไปเลยทั้งแปลง"</strong><br>ดินถมที่ดีต้องเป็นดินอนินทรีย์ ปราศจากรากไม้และซากพืช เพราะอินทรียวัตถุจะย่อยสลายและทิ้งโพรงไว้ใต้ดิน ทำให้พื้นทรุดเป็นหลุมภายหลัง วิธีที่ถูกคือถมด้วยดินถมและบดอัดให้ครบระดับก่อน แล้วค่อยปิดทับด้วยหน้าดิน 20–30 เซนติเมตรเฉพาะบริเวณที่จะจัดสวน</p>
<p><strong>ความเข้าใจผิดที่ 2: "ถมดินให้แน่น ๆ แล้วไม่ต้องตอกเข็มก็ได้"</strong><br>อาคารในพื้นที่นี้ถ่ายน้ำหนักลงเสาเข็มเสมอ ไม่ได้ฝากไว้กับดินถม การถมและบดอัดที่ดีมีไว้เพื่อไม่ให้พื้นวางบนดิน ถนนภายใน รั้ว และงานภูมิทัศน์ทรุดแยกจากตัวอาคาร ไม่ใช่เพื่อทดแทนฐานรากเสาเข็ม ผู้รับเหมาที่บอกว่าถมแน่นแล้วไม่ต้องตอกเข็ม คือสัญญาณอันตรายที่ควรเดินออกจากดีลทันที</p>
<h2>ขั้นตอนการทำงานถมที่ดิน 7 ขั้นตอน</h2>
<ol>
<li><strong>สำรวจหน้างานและวัดระดับ</strong> — เข้าวัดระดับพื้นที่เดิมด้วยกล้องระดับ เทียบกับระดับถนนสาธารณะหน้าที่ดิน ตรวจหมุดหลักเขต ทางเข้าออก และสภาพที่ดินข้างเคียง ฟรี ไม่มีค่าใช้จ่าย</li>
<li><strong>คำนวณปริมาณดินและออกใบเสนอราคาแยกรายการ</strong> — แจ้งปริมาตรดินแน่นที่ต้องใช้ ระดับที่จะถม ชนิดวัสดุ ระดับการบดอัด และตรวจว่าเข้าเกณฑ์ต้องแจ้งเจ้าพนักงานท้องถิ่นหรือไม่</li>
<li><strong>เตรียมพื้นที่</strong> — ตัดต้นไม้ กำจัดวัชพืช ปอกหน้าดินที่มีอินทรียวัตถุออก 15–30 เซนติเมตร ขนไปทิ้งให้เรียบร้อยก่อนถม</li>
<li><strong>ป้องกันที่ดินข้างเคียงและวางระบบระบายน้ำ</strong> — ทำแนวกันดินไหลและร่องระบายน้ำชั่วคราวก่อนนำดินเข้า เป็นทั้งข้อกำหนดตามกฎหมายและสาเหตุข้อพิพาทกับเพื่อนบ้านที่พบบ่อยที่สุด</li>
<li><strong>ขนดินเข้าและบดอัดเป็นชั้น</strong> — ปูดินชั้นละ 20–30 เซนติเมตร ควบคุมความชื้นให้ใกล้ค่าความชื้นเหมาะสม แล้วบดอัดด้วยรถบดสั่นสะเทือนจนครบระดับ</li>
<li><strong>ทดสอบความแน่นภาคสนามและวัดระดับปิดงาน</strong> — เก็บผลทดสอบความแน่นในชั้นที่กำหนด และวัดระดับหลังบดอัดเพื่อคำนวณปริมาตรคิวแน่นที่จะคิดเงินจริง</li>
<li><strong>ปรับระดับขั้นสุดท้ายและส่งมอบ</strong> — เกลี่ยให้ได้ความลาดระบายน้ำ ทำความสะอาดถนนสาธารณะหน้าไซต์ ส่งมอบพร้อมเอกสารผลทดสอบ ข้อมูลการวัดระดับ และใบรับแจ้ง (ถ้ามี)</li>
</ol>
