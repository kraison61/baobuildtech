<h2>ถมที่ดิน 1 ไร่ ใช้ดินกี่คิว และใช้เวลากี่วัน</h2>
<p>ที่ดิน 1 ไร่ (1,600 ตารางเมตร) ถมสูง 1 เมตร ต้องใช้ดินแน่น 1,600 คิว ซึ่งเท่ากับต้องสั่งดินหลวมเข้าหน้างานประมาณ 2,000 คิว หรือราว 180 เที่ยวรถ 10 ล้อ ใช้เวลาทำงานจริง 7–10 วัน สูตรคือ <strong>พื้นที่ (ตร.ม.) × ความหนาที่ถม (ม.) = ปริมาตรดินแน่น</strong> แล้วเผื่อการยุบตัวอีกประมาณ 25% เพื่อหาปริมาณดินหลวมที่ต้องสั่ง</p>
