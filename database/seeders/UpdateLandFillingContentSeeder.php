<h3>รับถมดินลูกรังสำหรับถนนภายในและลานจอดรถ</h3>
<p>รับถมดินลูกรังเหมาะกับงานที่ต้องรับน้ำหนักรถวิ่ง ได้แก่ ถนนภายในโครงการ ลานจอดรถ ทางเข้าไซต์ก่อสร้าง และชั้นรองพื้นทาง เพราะลูกรังมีการคละขนาดเม็ดที่ดี บดอัดแล้วได้ความแน่นสูงและระบายน้ำได้ ต่างจากดินถมทั่วไปที่อุ้มน้ำและอ่อนตัวเมื่อโดนฝน</p>
<p>ราคารับถมดินลูกรังอยู่ที่ประมาณ 380–500 บาทต่อคิวแน่น สูงกว่าดินถมทั่วไปเพราะเป็นวัสดุคัดจากบ่อ ไม่ใช่ดินขุดเหลือจากไซต์งานอื่น จุดที่ต้องระวังมี 2 ข้อ หนึ่ง ลูกรังให้ประโยชน์เต็มที่ก็ต่อเมื่อบดอัดจริง ถ้าเทกองแล้วเกลี่ยเฉย ๆ จะเป็นหลุมเป็นบ่อภายในหน้าฝนแรก สอง ไม่ควรใช้ลูกรังถมทั้งแปลงถ้าตั้งใจจะปลูกต้นไม้ เพราะรากพืชชอนไชได้ยาก</p>
<h3>สองความเข้าใจผิดที่ทำให้งานถมพังตั้งแต่เริ่ม</h3>
<p><strong>ความเข้าใจผิดที่ 1: "อยากปลูกต้นไม้ ก็ให้ถมด้วยดินร่วนไปเลยทั้งแปลง"</strong><br>ดินถมที่ดีต้องเป็นดินอนินทรีย์ ปราศจากรากไม้และซากพืช เพราะอินทรียวัตถุจะย่อยสลายและทิ้งโพรงไว้ใต้ดิน ทำให้พื้นทรุดเป็นหลุมในภายหลัง วิธีที่ถูกต้องคือถมด้วยดินถมและบดอัดให้ครบตามระดับก่อน แล้วค่อยปิดทับด้วยหน้าดินชั้นบนสุด 20–30 เซนติเมตรเฉพาะบริเวณที่จะจัดสวน</p>
<p><strong>ความเข้าใจผิดที่ 2: "ถมดินให้แน่น ๆ แล้วไม่ต้องตอกเข็มก็ได้"</strong><br>อาคารในกรุงเทพฯ และปริมณฑลถ่ายน้ำหนักลงเสาเข็มเสมอ ไม่ได้ฝากไว้กับดินถม การถมและบดอัดที่ดีมีไว้เพื่อไม่ให้ <strong>พื้นวางบนดิน ถนนภายใน รั้ว และงานภูมิทัศน์</strong> ทรุดแยกจากตัวอาคาร ไม่ใช่เพื่อทดแทนฐานรากเสาเข็ม ผู้รับเหมาที่บอกว่าถมแน่นแล้วไม่ต้องตอกเข็ม คือสัญญาณอันตรายที่ควรเดินออกจากดีลทันที</p>
<h2>ถมที่ดินต้องแจ้งเจ้าพนักงานท้องถิ่นไหม</h2>
<p>ขึ้นอยู่กับขนาดของเนินดิน <strong>ถ้าพื้นที่เนินดินเกิน 2,000 ตารางเมตร (ประมาณ 1 ไร่ 1 งาน) ต้องแจ้งการถมดินต่อเจ้าพนักงานท้องถิ่นก่อนเริ่มงาน</strong> ตามมาตรา 26 แห่งพระราชบัญญัติการขุดดินและถมดิน พ.ศ. 2543 และเริ่มถมได้ตั้งแต่วันที่ได้รับใบรับแจ้ง ส่วนพื้นที่ไม่เกิน 2,000 ตารางเมตร ไม่ต้องแจ้ง แต่ยังมีหน้าที่ตามกฎหมายเรื่องการระบายน้ำอยู่</p>
