<h3>ถมเสร็จแล้วสร้างบ้านได้เลยไหม</h3>
<p>ขึ้นอยู่กับว่าจะสร้างอะไร <strong>อาคารที่ลงเสาเข็มถ่ายน้ำหนักลงชั้นดินแข็งด้านล่าง เริ่มงานได้ทันทีหลังบดอัดผ่านเกณฑ์</strong> ไม่ต้องรอ 6–12 เดือน เพราะน้ำหนักอาคารไม่ได้ฝากไว้กับดินถม</p>
<p>สิ่งที่ต้องรอคือ <strong>งานที่วางอยู่บนดินถมโดยตรง</strong> เช่น พื้นวางบนดิน ถนนภายใน ลานคอนกรีต รั้ว และงานภูมิทัศน์ ส่วนนี้ควรรอให้ผ่านฤดูฝนอย่างน้อยหนึ่งรอบ หรือถ้าจำเป็นต้องทำเลย ให้ออกแบบเป็นพื้นวางบนเสาเข็มแทน คำแนะนำที่ว่า "ถมเสร็จต้องรอ 6–12 เดือนเสมอ" นั้นเหมารวมเกินไป และทำให้เจ้าของที่ดินเสียเวลาโดยไม่จำเป็น</p>
<h2>ถมที่ดินต้องแจ้งเจ้าพนักงานท้องถิ่นไหม</h2>
