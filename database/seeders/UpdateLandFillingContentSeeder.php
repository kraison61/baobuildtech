<ol>
<li><strong>สำรวจหน้างานและวัดระดับ</strong> — ทีมงานเข้าวัดระดับพื้นที่เดิมเทียบกับระดับถนนสาธารณะหน้าที่ดิน ตรวจสอบหมุดหลักเขต ทางเข้าออก และสภาพที่ดินข้างเคียง ฟรี ไม่มีค่าใช้จ่าย</li>
<li><strong>คำนวณปริมาณดินและออกใบเสนอราคาแยกรายการ</strong> — แจ้งปริมาตรดินแน่นที่ต้องใช้ ระดับที่จะถม ชนิดวัสดุ ระดับการบดอัด และตรวจสอบว่าเข้าเกณฑ์ต้องแจ้งเจ้าพนักงานท้องถิ่นหรือไม่</li>
<li><strong>เตรียมพื้นที่</strong> — ตัดต้นไม้ กำจัดวัชพืช และปอกหน้าดินที่มีอินทรียวัตถุออก 15–30 เซนติเมตร ขนไปทิ้งให้เรียบร้อยก่อนถม</li>
<li><strong>ป้องกันที่ดินข้างเคียงและวางระบบระบายน้ำ</strong> — ทำแนวกันดินไหลและร่องระบายน้ำชั่วคราวก่อนนำดินเข้า เพื่อไม่ให้ดินและน้ำไหลเข้าที่ดินข้างเคียง ซึ่งเป็นทั้งข้อกำหนดตามกฎหมายและสาเหตุข้อพิพาทกับเพื่อนบ้านที่พบบ่อยที่สุด</li>
<li><strong>ขนดินเข้าและบดอัดเป็นชั้น</strong> — ปูดินชั้นละ 20–30 เซนติเมตร ควบคุมความชื้นให้ใกล้ค่าความชื้นที่เหมาะสม แล้วบดอัดด้วยรถบดสั่นสะเทือนจนครบระดับที่กำหนด</li>
<li><strong>ทดสอบความแน่นภาคสนาม</strong> — เก็บผลทดสอบความแน่นในชั้นที่กำหนด เพื่อยืนยันว่าได้ตามเกณฑ์ก่อนถมชั้นถัดไป</li>
<li><strong>ปรับระดับขั้นสุดท้ายและส่งมอบ</strong> — เกลี่ยปรับระดับให้ได้ความลาดระบายน้ำ ทำความสะอาดถนนสาธารณะหน้าไซต์ และส่งมอบพร้อมเอกสารผลทดสอบและใบรับแจ้ง (ถ้ามี)</li>
