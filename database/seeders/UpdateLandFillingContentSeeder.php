    private function publishedItemUrl(string $slug): ?string
    {
        $item = ServiceItem::query()
            ->where('slug', $slug)
            ->where('is_published', true)
            ->first();

        if (! $item) {
            return null;
        }

        return route('services.items.show', [
            $item->service->category->slug,
            $item->service->slug,
            $item->slug,
        ], absolute: false);
    }

