<h2>ถมที่ดินโซนรังสิต ธัญบุรี ลำลูกกา ต้องถมสูงเท่าไหร่ถึงพ้นน้ำ</h2>
<p>ไม่มีตัวเลขมาตรฐานตัวเดียวที่ใช้ได้ทุกแปลง <strong>ระดับที่ถูกต้องต้องคำนวณจากสามค่าประกอบกัน</strong> คือระดับหลังถนนสาธารณะหน้าที่ดิน ระดับน้ำท่วมสูงสุดที่เคยเกิดในซอยนั้น และค่าเผื่อการทรุดตัวในอนาคต ที่ดินสองแปลงติดกันในตำบลเดียวกันอาจต้องถมต่างกัน 30–40 เซนติเมตรได้ ถ้าอยู่คนละฝั่งคลอง</p>
<h3>วิธีหาระดับถมที่ถูกต้องสำหรับที่ดินของคุณ</h3>
<ol>
<li><strong>วัดระดับหลังถนนหน้าที่ดิน</strong> เป็นจุดอ้างอิงหลัก ที่ดินที่ต่ำกว่าหลังถนนจะรับน้ำจากถนนเข้ามาเสมอในหน้าฝน</li>
<li><strong>ถามเพื่อนบ้านที่อยู่มานาน</strong> ว่าน้ำเคยขึ้นสูงสุดถึงระดับไหนและปีไหน โซนทุ่งรังสิตเป็นพื้นที่ราบลุ่มที่อาศัยระบบคลองรังสิตประยูรศักดิ์และประตูระบายน้ำในการควบคุม จึงมีประวัติน้ำท่วมที่ต่างกันชัดเจนระหว่างพื้นที่ในเขตคันกั้นน้ำกับนอกคันกั้นน้ำ</li>
<li><strong>เผื่อระดับทรุดตัว</strong> ตามความหนาที่ถมและสภาพชั้นดินเดิม ถมพอดีระดับที่ต้องการวันนี้ ปีหน้าจะต่ำกว่าที่ตั้งใจไว้</li>
