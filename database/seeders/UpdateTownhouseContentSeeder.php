    private function publishedItemUrl(string $slug): ?string
    {
        $item = ServiceItem::query()
            ->where('slug', $slug)
            ->where('is_published', true)
            ->with('service.category')
            ->first();

        return $item?->url();
    }

    private function publishedServiceUrl(string $slug): ?string
    {
        $service = Service::query()
            ->where('slug', $slug)
            ->where('is_published', true)
            ->with('category')
            ->first();

        return $service?->url();
    }
