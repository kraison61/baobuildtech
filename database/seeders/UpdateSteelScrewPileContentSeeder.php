<li><strong>ค่าในตารางยังไม่ใช่น้ำหนักที่ใช้งานได้จริง</strong> สำหรับรุ่นยาว 2 เมตร วิศวกรผู้ออกแบบกำหนด Safety Factor ได้ระหว่าง 2.5–4 ตามชั้นดินและน้ำหนักโครงสร้าง ตัวอย่างเช่น รุ่น FS68 (Qu 7.44 ตัน) หารด้วย 2.5–4 จะได้น้ำหนักใช้งานประมาณ 1.9–3.0 ตันต่อต้น</li>
<li><strong>ค่าเปลี่ยนตามดิน</strong> เอกสารระบุว่าค่า Qu เปลี่ยนแปลงได้ตามค่าความเชื่อมแน่นระหว่างเม็ดดิน (C) และการทดสอบรุ่น 2 เมตรทำที่ฉะเชิงเทรา ไม่ใช่ปทุมธานีหรือนนทบุรี</li>
<li><strong>ตรวจสอบระหว่างติดตั้งด้วยแรงบิด (Torque)</strong> มาตรฐานสากลใช้วิธีนี้ควบคุมคุณภาพ เสาเข็มเกลียวประเมินกำลังรับน้ำหนักทั้งแรงกดและแรงดึงจากแรงบิดสุดท้ายขณะติดตั้ง โดยใช้ตัวคูณที่เรียกว่า Kt ตัวอย่างเช่น ICC-ES AC358 กำหนดค่า Kt เริ่มต้นไว้ที่ 9 ft⁻¹ สำหรับท่อกลม OD 2.875 นิ้ว และ 7 ft⁻¹ สำหรับท่อ OD 3.5 นิ้ว อย่างไรก็ตาม งานวิจัยจากผลทดสอบ 799 ครั้งพบว่าค่า Kt ตาม AC358 ประเมินกำลังต่ำเกินจริงเมื่อแรงบิดต่ำ และสูงเกินจริงเมื่อแรงบิดสูง ถ้าต้องการความแน่นอน จึงควรทดสอบรับน้ำหนักที่หน้างานจริง</li>
</ol>

<h2>เสาเข็มเหล็กไมโครไพล์ ต่างจากไมโครไพล์คอนกรีตอย่างไร?</h2>
<p>สองแบบนี้ต่างกันที่วิธีติดตั้งและกลไกการรับน้ำหนัก ไมโครไพล์แบบเหล็กใช้วิธีเจาะแล้วอัดน้ำปูน ส่วนไมโครไพล์คอนกรีตที่นิยมในไทยใช้วิธีตอกหรือกดเสาคอนกรีตสำเร็จรูปลงไปทีละท่อน</p>
