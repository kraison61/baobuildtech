<tr><td>กลไกรับน้ำหนัก</td><td>แบกทานที่ปีกเกลียว</td><td>แรงเสียดทานระหว่างน้ำปูนกับดิน โดยทั่วไปไม่นับแรงแบกทานที่ปลาย</td><td>แรงเสียดทานและแรงแบกทานที่ปลาย</td></tr>
