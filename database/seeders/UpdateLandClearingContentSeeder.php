<li><strong>ก่อนรังวัดหรือแบ่งแปลง</strong> — เจ้าหน้าที่ที่ดินต้องเข้าถึงหมุดได้</li>
<li><strong>ก่อนประกาศขายหรือให้เช่า</strong> — ผู้ซื้อเห็นขนาดและสภาพจริง ตัดสินใจง่ายขึ้น</li>
<li><strong>ที่ดินที่ปล่อยทิ้งร้าง</strong> — ตาม พ.ร.บ.ภาษีที่ดินและสิ่งปลูกสร้าง พ.ศ. 2562 ที่ดินที่ถูกประเมินว่าทิ้งร้างว่างเปล่าเสียภาษีในอัตราสูงกว่าที่ดินที่ใช้ประโยชน์ เจ้าของหลายรายจึงเคลียร์ที่เพื่อปรับไปใช้ประโยชน์ ควรสอบถามเงื่อนไขกับ อบต. หรือเทศบาลในพื้นที่ก่อน</li>
<li><strong>หน้าแล้งที่หญ้าแห้ง</strong> — ลดความเสี่ยงไฟไหม้หญ้า งู สัตว์มีพิษ และการลักลอบทิ้งขยะ</li>
