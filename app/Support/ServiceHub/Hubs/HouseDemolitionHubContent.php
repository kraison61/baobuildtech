    public function serviceAreaText(): string
    {
        $areas = implode(' · ', Company::serviceAreas(includeCountry: false));
        $district = (string) (config('company.address.district') ?? '');
        $province = (string) (config('company.address.province') ?? '');
        $office = trim($district.' '.$province);

        $officeText = $office !== '' ? " สำนักงานอยู่{$office}" : '';

        return "พื้นที่ให้บริการ: {$areas}{$officeText} สำรวจหน้างานฟรีในเขตให้บริการ ต่างจังหวัดพิจารณาเป็นรายกรณีตามขนาดงาน";
    }

