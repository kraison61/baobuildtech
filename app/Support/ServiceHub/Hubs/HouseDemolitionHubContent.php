    private function itemHref(string $slug): string
    {
        $item = $this->publishedItems()->firstWhere('slug', $slug);

        return $item?->url() ?? '#services';
    }

    private function itemCover(string $slug): string
    {
        $cover = $this->publishedItems()->firstWhere('slug', $slug)?->cover_image;

        return filled($cover) ? (string) $cover : '';
    }
